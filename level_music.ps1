# Measures how loud each track in Audio/music is and writes Scripts/autoload/music_levels.gd, so every song plays
# at the same loudness (TARGET_LUFS) no matter how loud the file itself is. export_web.ps1 runs this before every
# export; run it by hand after adding music if you test in the editor.
# Needs ffmpeg (winget install Gyan.FFmpeg). Tracks already measured (same name and size) are skipped.

$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

$TARGET_LUFS = -20.0
$MAX_PEAK_DB = -1.0  # never boost a track so far that its loudest moment would clip
$cachePath = "Audio\music\.levels_cache.json"
$outPath = "Scripts\autoload\music_levels.gd"

if (-not (Get-Command ffmpeg -ErrorAction SilentlyContinue)) {
    Write-Host "ffmpeg not found: music levels not updated (songs play at their own volume)."
    return
}

$cache = @{}
if (Test-Path $cachePath) {
    (Get-Content $cachePath -Raw | ConvertFrom-Json).PSObject.Properties | ForEach-Object { $cache[$_.Name] = $_.Value }
}

$gains = [ordered]@{}
$newCache = @{}
foreach ($f in Get-ChildItem "Audio\music" -File | Where-Object { $_.Extension -in ".ogg", ".mp3", ".wav" } | Sort-Object Name) {
    $key = $f.Name.ToLower()
    $entry = $cache[$key]
    if (-not $entry -or $entry.size -ne $f.Length) {
        # ffmpeg reports on stderr; go through cmd so Windows PowerShell doesn't treat that as an error
        $out = cmd /c "ffmpeg -hide_banner -nostats -i `"$($f.FullName)`" -af ebur128=peak=true -f null - 2>&1" | Out-String
        $lufs = [double]([regex]::Matches($out, "I:\s+(-?[\d.]+) LUFS") | Select-Object -Last 1).Groups[1].Value
        $peak = [double]([regex]::Matches($out, "Peak:\s+(-?[\d.]+) dBFS") | Select-Object -Last 1).Groups[1].Value
        $entry = [pscustomobject]@{ size = $f.Length; lufs = $lufs; peak = $peak }
        Write-Host ("Measured {0}: {1} LUFS, peak {2} dBFS" -f $f.Name, $lufs, $peak)
    }
    $newCache[$key] = $entry
    $gain = [math]::Min($TARGET_LUFS - $entry.lufs, $MAX_PEAK_DB - $entry.peak)
    $gains[$f.BaseName.ToLower()] = [math]::Round($gain, 1)
}

$newCache | ConvertTo-Json | Set-Content $cachePath -Encoding utf8
$lines = @(
    "# Generated by level_music.ps1 - don't edit by hand; re-run it after adding or changing music.",
    "# Volume correction in dB per track (lowercase name without extension) so every song plays at $TARGET_LUFS LUFS.",
    "const GAIN_DB := {"
)
foreach ($name in $gains.Keys) { $lines += ("`t`"{0}`": {1}," -f $name, $gains[$name].ToString([Globalization.CultureInfo]::InvariantCulture)) }
$lines += "}"
[IO.File]::WriteAllText((Join-Path $PSScriptRoot $outPath), ($lines -join "`n") + "`n", (New-Object Text.UTF8Encoding $false))
Write-Host "Music levels written to $outPath"
